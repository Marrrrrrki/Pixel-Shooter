class WaveManager:

    def __init__(self):

        self.wave = 1

    # =========================================================
    # CURRENT WAVE
    # =========================================================

    def get_wave(self):

        return self.wave

    # =========================================================
    # NEXT WAVE
    # =========================================================

    def next_wave(self):

        self.wave += 1

        return self.wave

    # =========================================================
    # RESET
    # =========================================================

    def reset(self):

        self.wave = 1